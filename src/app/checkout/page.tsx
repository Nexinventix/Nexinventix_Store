
"use client";

import { FormEvent, useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import {
  ArrowLeft,
  ArrowRight,
  ShieldCheck,
  LockKeyhole,
  MapPin,
  LoaderCircle,
  ShoppingBag,
} from "lucide-react";

import Header from "@/components/Header/Header";
import Footer from "@/components/Footer/Footer";
import { useCart } from "@/context/CartContext";
import styles from "./Checkout.module.css";

type CheckoutForm = {
  firstName: string;
  lastName: string;
  email: string;
  phone: string;
  address: string;
  city: string;
  state: string;
  deliveryNote: string;
};

const initialForm: CheckoutForm = {
  firstName: "",
  lastName: "",
  email: "",
  phone: "",
  address: "",
  city: "",
  state: "Lagos",
  deliveryNote: "",
};

const states = [
  "Abia", "Adamawa", "Akwa Ibom", "Anambra", "Bauchi",
  "Bayelsa", "Benue", "Borno", "Cross River", "Delta",
  "Ebonyi", "Edo", "Ekiti", "Enugu", "FCT",
  "Gombe", "Imo", "Jigawa", "Kaduna", "Kano",
  "Katsina", "Kebbi", "Kogi", "Kwara", "Lagos",
  "Nasarawa", "Niger", "Ogun", "Ondo", "Osun",
  "Oyo", "Plateau", "Rivers", "Sokoto", "Taraba",
  "Yobe", "Zamfara",
];

function formatPrice(amount: number) {
  return new Intl.NumberFormat("en-NG", {
    style: "currency",
    currency: "NGN",
    maximumFractionDigits: 2,
  }).format(amount);
}

export default function CheckoutPage() {
  const router = useRouter();
  const { items, subtotal } = useCart();

  const [form, setForm] = useState<CheckoutForm>(initialForm);
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState("");

  function updateField(
    field: keyof CheckoutForm,
    value: string
  ) {
    setForm((current) => ({
      ...current,
      [field]: value,
    }));
  }

  async function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    setError("");

    if (items.length === 0) {
      setError("Your cart is empty. Please add products before checkout.");
      return;
    }

    if (form.phone.trim().length < 7) {
      setError("Please enter a valid phone number.");
      return;
    }

    setSubmitting(true);

    try {
      // Send product IDs and quantities, not trusted client prices.
      // The server must calculate the actual amount from the database.
      const response = await fetch("/api/checkout/initialize", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          customer: {
            firstName: form.firstName.trim(),
            lastName: form.lastName.trim(),
            email: form.email.trim().toLowerCase(),
            phone: form.phone.trim(),
          },
          delivery: {
            address: form.address.trim(),
            city: form.city.trim(),
            state: form.state,
            note: form.deliveryNote.trim(),
          },
          items: items.map((item) => ({
            productId: item.id,
            quantity: item.quantity,
          })),
        }),
      });

      const result = await response.json();

      if (!response.ok || !result.success) {
        throw new Error(
          result.message || "Unable to initialize your payment."
        );
      }

      if (
        typeof result.authorizationUrl !== "string" ||
        !result.authorizationUrl.startsWith("https://checkout.paystack.com/")
      ) {
        throw new Error("The payment service returned an invalid checkout URL.");
      }

      // The server returns a URL generated by Paystack.
      window.location.assign(result.authorizationUrl);
    } catch (err) {
      setError(
        err instanceof Error
          ? err.message
          : "Something went wrong. Please try again."
      );
      setSubmitting(false);
    }
  }

  return (
    <>
      <Header />

      <main className={styles.page}>
        <div className={styles.container}>
          <Link href="/cart" className={styles.backLink}>
            <ArrowLeft size={17} />
            Back to cart
          </Link>

          <div className={styles.heading}>
            <span className={styles.eyebrow}>SECURE CHECKOUT</span>
            <h1>Complete your order<span>.</span></h1>
            <p>
              Enter your details and continue to Paystack to complete
              your payment securely.
            </p>
          </div>

          {items.length === 0 ? (
            <section className={styles.emptyState}>
              <ShoppingBag size={42} />
              <h2>Your cart is empty</h2>
              <p>Add products to your cart before checking out.</p>
              <Link href="/shop" className={styles.primaryButton}>
                Explore products
                <ArrowRight size={17} />
              </Link>
            </section>
          ) : (
            <form onSubmit={handleSubmit} className={styles.layout}>
              <div className={styles.formColumn}>
                <section className={styles.panel}>
                  <div className={styles.panelHeading}>
                    <span className={styles.step}>01</span>
                    <div>
                      <h2>Contact information</h2>
                      <p>How can we reach you about your order?</p>
                    </div>
                  </div>

                  <div className={styles.fieldGrid}>
                    <label className={styles.field}>
                      <span>First name *</span>
                      <input
                        required
                        autoComplete="given-name"
                        value={form.firstName}
                        onChange={(e) =>
                          updateField("firstName", e.target.value)
                        }
                        placeholder="First name"
                      />
                    </label>

                    <label className={styles.field}>
                      <span>Last name *</span>
                      <input
                        required
                        autoComplete="family-name"
                        value={form.lastName}
                        onChange={(e) =>
                          updateField("lastName", e.target.value)
                        }
                        placeholder="Last name"
                      />
                    </label>

                    <label className={styles.field}>
                      <span>Email address *</span>
                      <input
                        type="email"
                        required
                        autoComplete="email"
                        value={form.email}
                        onChange={(e) =>
                          updateField("email", e.target.value)
                        }
                        placeholder="you@example.com"
                      />
                      <small>Used for your payment receipt and order updates.</small>
                    </label>

                    <label className={styles.field}>
                      <span>Phone number *</span>
                      <input
                        type="tel"
                        required
                        autoComplete="tel"
                        value={form.phone}
                        onChange={(e) =>
                          updateField("phone", e.target.value)
                        }
                        placeholder="e.g. 08012345678"
                      />
                    </label>
                  </div>
                </section>

                <section className={styles.panel}>
                  <div className={styles.panelHeading}>
                    <span className={styles.step}>02</span>
                    <div>
                      <h2>Delivery address</h2>
                      <p>Where should we deliver your order?</p>
                    </div>
                    <MapPin size={22} className={styles.headingIcon} />
                  </div>

                  <div className={styles.fieldGrid}>
                    <label className={`${styles.field} ${styles.fullWidth}`}>
                      <span>Street address *</span>
                      <input
                        required
                        autoComplete="street-address"
                        value={form.address}
                        onChange={(e) =>
                          updateField("address", e.target.value)
                        }
                        placeholder="House number, street and area"
                      />
                    </label>

                    <label className={styles.field}>
                      <span>City or town *</span>
                      <input
                        required
                        autoComplete="address-level2"
                        value={form.city}
                        onChange={(e) =>
                          updateField("city", e.target.value)
                        }
                        placeholder="e.g. Ajegunle"
                      />
                    </label>

                    <label className={styles.field}>
                      <span>State *</span>
                      <select
                        required
                        autoComplete="address-level1"
                        value={form.state}
                        onChange={(e) =>
                          updateField("state", e.target.value)
                        }
                      >
                        {states.map((state) => (
                          <option key={state} value={state}>
                            {state}
                          </option>
                        ))}
                      </select>
                    </label>

                    <label className={`${styles.field} ${styles.fullWidth}`}>
                      <span>Delivery instructions (optional)</span>
                      <textarea
                        rows={3}
                        value={form.deliveryNote}
                        onChange={(e) =>
                          updateField("deliveryNote", e.target.value)
                        }
                        placeholder="Landmarks or other delivery instructions"
                      />
                    </label>
                  </div>
                </section>

                <section className={styles.paymentPanel}>
                  <div className={styles.paymentIcon}>
                    <ShieldCheck size={24} />
                  </div>
                  <div>
                    <h3>Pay securely with Paystack</h3>
                    <p>
                      You will be redirected to Paystack's secure
                      checkout to complete your payment.
                    </p>
                  </div>
                  <span className={styles.paymentLabel}>PAYSTACK</span>
                </section>

                {error && (
                  <div className={styles.error} role="alert">
                    {error}
                  </div>
                )}

                <button
                  type="submit"
                  className={styles.submitButton}
                  disabled={submitting || items.length === 0}
                >
                  {submitting ? (
                    <>
                      <LoaderCircle size={19} className={styles.spinner} />
                      Preparing secure payment...
                    </>
                  ) : (
                    <>
                      Continue to Paystack
                      <ArrowRight size={18} />
                    </>
                  )}
                </button>

                <p className={styles.secureNote}>
                  <LockKeyhole size={15} />
                  Your payment details are handled by Paystack.
                  Never share your card PIN or OTP with anyone.
                </p>
              </div>

              <aside className={styles.summary}>
                <h2>Order summary</h2>

                <div className={styles.summaryItems}>
                  {items.map((item) => (
                    <div key={item.id} className={styles.summaryItem}>
                      <div className={styles.itemImage}>
                        {item.image ? (
                          <img src={item.image} alt="" />
                        ) : (
                          <ShoppingBag size={22} />
                        )}
                        <span>{item.quantity}</span>
                      </div>

                      <div className={styles.itemDetails}>
                        <strong>{item.name}</strong>
                        {item.brand && <small>{item.brand}</small>}
                        <span>{formatPrice(item.price * item.quantity)}</span>
                      </div>
                    </div>
                  ))}
                </div>

                <div className={styles.summaryRow}>
                  <span>Subtotal</span>
                  <strong>{formatPrice(subtotal)}</strong>
                </div>

                <div className={styles.summaryRow}>
                  <span>Delivery</span>
                  <span className={styles.deliveryNote}>
                    Confirmed by server
                  </span>
                </div>

                <div className={styles.summaryTotal}>
                  <span>Estimated subtotal</span>
                  <strong>{formatPrice(subtotal)}</strong>
                </div>

                <p className={styles.summaryDisclaimer}>
                  This is an estimate based on your current cart.
                  The server will validate product prices and stock
                  and calculate any applicable delivery fee before
                  initializing payment.
                </p>

                <Link href="/cart" className={styles.editCart}>
                  <ArrowLeft size={15} />
                  Edit cart
                </Link>
              </aside>
            </form>
          )}
        </div>
      </main>

      <Footer />
    </>
  );
}